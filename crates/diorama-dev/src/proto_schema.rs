//! Compile upstream Kubernetes `.proto` files into a static Rust schema table.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::{Result, read_bounded};

/// Upstream Kubernetes release tag used to generate the committed schema.
pub const DEFAULT_UPSTREAM_VERSION: &str = "v1.37.1";
/// Upstream Kubernetes commit SHA corresponding to [`DEFAULT_UPSTREAM_VERSION`].
pub const DEFAULT_UPSTREAM_COMMIT: &str = "f78e722310e50bcaca9276be22276d9e91d91308";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum WireKind {
    String,
    Bytes,
    Bool,
    Int32,
    Int64,
    Uint32,
    Uint64,
    Sint32,
    Sint64,
    Float,
    Double,
    Message,
    Enum,
}

impl WireKind {
    const fn as_rust(self) -> &'static str {
        match self {
            Self::String => "WireKind::String",
            Self::Bytes => "WireKind::Bytes",
            Self::Bool => "WireKind::Bool",
            Self::Int32 => "WireKind::Int32",
            Self::Int64 => "WireKind::Int64",
            Self::Uint32 => "WireKind::Uint32",
            Self::Uint64 => "WireKind::Uint64",
            Self::Sint32 => "WireKind::Sint32",
            Self::Sint64 => "WireKind::Sint64",
            Self::Float => "WireKind::Float",
            Self::Double => "WireKind::Double",
            Self::Message => "WireKind::Message",
            Self::Enum => "WireKind::Enum",
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
struct RawField {
    number: u32,
    name: String,
    type_name: String,
    repeated: bool,
    map_value: String,
}

#[derive(Clone, Debug, PartialEq, Eq)]
struct ResolvedField {
    number: u32,
    name: String,
    kind: WireKind,
    type_name: String,
    repeated: bool,
    map_value: Option<WireKind>,
    map_value_type: String,
}

/// Collect `.proto` files recursively under `dir` in deterministic path order.
pub fn collect_proto_files(dir: &Path) -> Result<BTreeSet<PathBuf>> {
    let mut out = BTreeSet::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(current) = stack.pop() {
        for entry in std::fs::read_dir(&current)? {
            let entry = entry?;
            let path = entry.path();
            let file_type = entry.file_type()?;
            if file_type.is_dir() {
                stack.push(path);
            } else if file_type.is_file()
                && path.extension().and_then(|ext| ext.to_str()) == Some("proto")
            {
                out.insert(path);
            }
        }
    }
    if out.is_empty() {
        return Err(format!("no .proto files found in {}", dir.display()).into());
    }
    Ok(out)
}

/// Generate the Rust source for `k8s_proto_schema.rs` from a directory of `.proto` files.
pub fn generate_from_dir(dir: &Path, version: &str, commit: &str) -> Result<String> {
    let files = collect_proto_files(dir)?;
    let mut sources = Vec::with_capacity(files.len());
    for file in files {
        let bytes = read_bounded(&file, 8 * 1024 * 1024)?;
        let content = String::from_utf8(bytes)?;
        sources.push(content);
    }
    Ok(generate_from_sources(&sources, version, commit))
}

/// Generate the Rust source for `k8s_proto_schema.rs` from in-memory `.proto` texts.
#[must_use]
pub fn generate_from_sources<S: AsRef<str>>(sources: &[S], version: &str, commit: &str) -> String {
    let mut raw_messages: BTreeMap<String, Vec<RawField>> = BTreeMap::new();
    let mut enums: BTreeMap<String, BTreeMap<i64, String>> = BTreeMap::new();
    for source in sources {
        parse_proto(source.as_ref(), &mut raw_messages, &mut enums);
    }
    let known_messages: BTreeSet<String> = raw_messages.keys().cloned().collect();
    let mut messages: BTreeMap<String, Vec<ResolvedField>> = BTreeMap::new();
    for (message, fields) in raw_messages {
        let package = package_of(&message);
        let mut resolved: Vec<ResolvedField> = fields
            .into_iter()
            .map(|field| resolve_field(&message, package, field, &known_messages, &enums))
            .collect();
        resolved.sort_by_key(|field| field.number);
        resolved.dedup_by_key(|field| field.number);
        messages.insert(message, resolved);
    }
    render_rust(&messages, &enums, version, commit)
}

fn render_rust(
    messages: &BTreeMap<String, Vec<ResolvedField>>,
    enums: &BTreeMap<String, BTreeMap<i64, String>>,
    version: &str,
    commit: &str,
) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// This file is @generated by `diorama-proto-schema` from kubernetes/kubernetes {version} ({commit})."
    );
    let _ = writeln!(out, "// Do not edit manually.");
    let _ = writeln!(out);
    let _ = writeln!(out, "static MESSAGES: &[(&str, &[FieldDef])] = &[");
    for (message, fields) in messages {
        if fields.is_empty() {
            let _ = writeln!(out, "    ({message:?}, &[]),");
            continue;
        }
        let _ = writeln!(out, "    ({message:?}, &[");
        for field in fields {
            let _ = writeln!(out, "        {},", format_field(field));
        }
        let _ = writeln!(out, "    ]),");
    }
    let _ = writeln!(out, "];");
    let _ = writeln!(out);
    let _ = writeln!(out, "static ENUMS: &[(&str, &[(i64, &str)])] = &[");
    for (enum_name, values) in enums {
        if values.is_empty() {
            let _ = writeln!(out, "    ({enum_name:?}, &[]),");
            continue;
        }
        let _ = writeln!(out, "    ({enum_name:?}, &[");
        for (number, label) in values {
            let _ = writeln!(out, "        ({number}, {label:?}),");
        }
        let _ = writeln!(out, "    ]),");
    }
    let _ = writeln!(out, "];");
    out
}

fn format_field(field: &ResolvedField) -> String {
    if let Some(map_kind) = field.map_value {
        return format!(
            "FieldDef::map({}, {:?}, {}, {:?})",
            field.number,
            field.name,
            map_kind.as_rust(),
            field.map_value_type
        );
    }
    if field.type_name.is_empty() || !matches!(field.kind, WireKind::Message | WireKind::Enum) {
        if field.repeated {
            format!(
                "FieldDef::repeated_scalar({}, {:?}, {})",
                field.number,
                field.name,
                field.kind.as_rust()
            )
        } else {
            format!(
                "FieldDef::scalar({}, {:?}, {})",
                field.number,
                field.name,
                field.kind.as_rust()
            )
        }
    } else if field.repeated {
        format!(
            "FieldDef::repeated_typed({}, {:?}, {}, {:?})",
            field.number,
            field.name,
            field.kind.as_rust(),
            field.type_name
        )
    } else {
        format!(
            "FieldDef::typed({}, {:?}, {}, {:?})",
            field.number,
            field.name,
            field.kind.as_rust(),
            field.type_name
        )
    }
}

fn package_of(message: &str) -> &str {
    message.rsplit_once('.').map_or("", |(package, _)| package)
}

fn resolve_field(
    message: &str,
    package: &str,
    field: RawField,
    messages: &BTreeSet<String>,
    enums: &BTreeMap<String, BTreeMap<i64, String>>,
) -> ResolvedField {
    let map = !field.map_value.is_empty();
    let type_token = if map {
        field.map_value.as_str()
    } else {
        field.type_name.as_str()
    };
    let resolved = resolve_type(message, package, type_token, messages, enums);
    let kind = scalar_kind(type_token, &resolved, messages, enums);
    let map_value = if map {
        Some(scalar_kind(&field.map_value, &resolved, messages, enums))
    } else {
        None
    };
    let map_value_type = if map && matches!(map_value, Some(WireKind::Message | WireKind::Enum)) {
        resolved.clone()
    } else {
        String::new()
    };
    let type_name = if !map && matches!(kind, WireKind::Message | WireKind::Enum) {
        resolved
    } else {
        String::new()
    };
    ResolvedField {
        number: field.number,
        name: field.name,
        kind: if map { WireKind::Message } else { kind },
        type_name,
        repeated: field.repeated || map,
        map_value,
        map_value_type,
    }
}

fn resolve_type(
    message: &str,
    package: &str,
    type_name: &str,
    messages: &BTreeSet<String>,
    enums: &BTreeMap<String, BTreeMap<i64, String>>,
) -> String {
    let type_name = type_name.trim_start_matches('.');
    if type_name.contains('.') {
        return type_name.to_string();
    }
    for candidate in [
        format!("{message}.{type_name}"),
        format!("{package}.{type_name}"),
    ] {
        if messages.contains(&candidate) || enums.contains_key(&candidate) {
            return candidate;
        }
    }
    type_name.to_string()
}

fn scalar_kind(
    type_token: &str,
    resolved: &str,
    messages: &BTreeSet<String>,
    enums: &BTreeMap<String, BTreeMap<i64, String>>,
) -> WireKind {
    match type_token.trim_start_matches('.') {
        "string" => WireKind::String,
        "bytes" => WireKind::Bytes,
        "bool" => WireKind::Bool,
        "int32" | "fixed32" | "sfixed32" => WireKind::Int32,
        "int64" | "fixed64" | "sfixed64" => WireKind::Int64,
        "uint32" => WireKind::Uint32,
        "uint64" => WireKind::Uint64,
        "sint32" => WireKind::Sint32,
        "sint64" => WireKind::Sint64,
        "float" => WireKind::Float,
        "double" => WireKind::Double,
        _ if enums.contains_key(resolved) => WireKind::Enum,
        _ if messages.contains(resolved) => WireKind::Message,
        _ => WireKind::Message,
    }
}

enum Scope {
    Message(String),
    Enum(String),
    Oneof,
}

fn parse_proto(
    source: &str,
    messages: &mut BTreeMap<String, Vec<RawField>>,
    enums: &mut BTreeMap<String, BTreeMap<i64, String>>,
) {
    let text = strip_comments(source);
    let mut package = String::new();
    let mut stack: Vec<Scope> = Vec::new();
    let mut buf = String::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        buf.push(' ');
        buf.push_str(line);
        if !buf.contains('{') && !buf.contains('}') && !buf.contains(';') {
            continue;
        }
        let stmt = std::mem::take(&mut buf);
        let stmt = stmt.trim();
        if let Some(rest) = stmt.strip_prefix("package ") {
            package = rest.trim().trim_end_matches(';').trim().to_string();
            continue;
        }
        if stmt.starts_with("import ") || stmt.starts_with("option ") || stmt.starts_with("syntax ")
        {
            continue;
        }
        if stmt.starts_with('}')
            || stmt.ends_with('}')
                && !stmt.contains("message ")
                && !stmt.contains("enum ")
                && !stmt.contains("oneof ")
        {
            stack.pop();
            continue;
        }
        if let Some(name) = decl_name(stmt, "message ") {
            let full = qualify(&package, &stack, &name);
            stack.push(Scope::Message(full.clone()));
            messages.entry(full).or_default();
            continue;
        }
        if let Some(name) = decl_name(stmt, "enum ") {
            let full = qualify(&package, &stack, &name);
            stack.push(Scope::Enum(full.clone()));
            enums.entry(full).or_default();
            continue;
        }
        if decl_name(stmt, "oneof ").is_some() {
            stack.push(Scope::Oneof);
            continue;
        }
        if let Some(message) = stack.iter().rev().find_map(|scope| match scope {
            Scope::Message(message) => Some(message.clone()),
            Scope::Enum(_) | Scope::Oneof => None,
        }) {
            if let Some(Scope::Enum(name)) = stack.last() {
                if let Some((label, number)) = parse_enum_value(stmt) {
                    enums.entry(name.clone()).or_default().insert(number, label);
                }
            } else if let Some(field) = parse_field(stmt) {
                messages.entry(message).or_default().push(field);
            }
        } else if let Some(Scope::Enum(name)) = stack.last()
            && let Some((label, number)) = parse_enum_value(stmt)
        {
            enums.entry(name.clone()).or_default().insert(number, label);
        }
    }
}

fn qualify(package: &str, stack: &[Scope], name: &str) -> String {
    let mut parts = Vec::new();
    if !package.is_empty() {
        parts.push(package.to_string());
    }
    for scope in stack {
        if let Scope::Message(message) = scope {
            let short = message.rsplit('.').next().unwrap_or(message);
            parts.push(short.to_string());
        }
    }
    parts.push(name.to_string());
    parts.join(".")
}

fn decl_name(stmt: &str, prefix: &str) -> Option<String> {
    let rest = stmt.trim().strip_prefix(prefix)?;
    let name = rest
        .split(|ch: char| ch == '{' || ch.is_whitespace())
        .next()?;
    if name.is_empty() {
        None
    } else {
        Some(name.to_string())
    }
}

fn parse_field(stmt: &str) -> Option<RawField> {
    let stmt = stmt.trim().trim_end_matches(';').trim();
    let stmt = stmt.split('[').next()?.trim();
    if stmt.is_empty() || stmt.starts_with("reserved") || stmt.starts_with("extensions") {
        return None;
    }
    let (head, number) = stmt.rsplit_once('=')?;
    let number = number.trim().parse().ok()?;
    let mut head = head.trim();
    let mut repeated = false;
    for keyword in ["optional ", "required ", "repeated "] {
        if let Some(rest) = head.strip_prefix(keyword) {
            repeated = keyword.starts_with("repeated");
            head = rest.trim();
            break;
        }
    }
    let (type_token, name) = head.rsplit_once(char::is_whitespace)?;
    let name = name.trim();
    if name.is_empty() {
        return None;
    }
    let mut type_name = type_token.trim().to_string();
    let mut map_value = String::new();
    if let Some(inner) = type_name
        .strip_prefix("map<")
        .and_then(|value| value.strip_suffix('>'))
    {
        let (_, value) = inner.split_once(',')?;
        map_value = value.trim().to_string();
        type_name.clear();
        repeated = true;
    }
    Some(RawField {
        number,
        name: name.to_string(),
        type_name,
        repeated,
        map_value,
    })
}

fn parse_enum_value(stmt: &str) -> Option<(String, i64)> {
    let stmt = stmt.trim().trim_end_matches(';').trim();
    let stmt = stmt.split('[').next()?.trim();
    let (name, number) = stmt.split_once('=')?;
    let name = name.trim();
    if name.is_empty() || name.contains(' ') {
        return None;
    }
    Some((name.to_string(), number.trim().parse().ok()?))
}

fn strip_comments(source: &str) -> String {
    let bytes = source.as_bytes();
    let mut out = String::with_capacity(source.len());
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index] == b'/' && index + 1 < bytes.len() && bytes[index + 1] == b'/' {
            index += 2;
            while index < bytes.len() && bytes[index] != b'\n' {
                index += 1;
            }
            continue;
        }
        if bytes[index] == b'/' && index + 1 < bytes.len() && bytes[index + 1] == b'*' {
            index += 2;
            while index + 1 < bytes.len() && !(bytes[index] == b'*' && bytes[index + 1] == b'/') {
                index += 1;
            }
            index = (index + 2).min(bytes.len());
            continue;
        }
        out.push(bytes[index] as char);
        index += 1;
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_sorted_static_tables_from_proto_source() {
        let proto = r#"
            syntax = "proto2";
            package k8s.io.api.core.v1;
            enum Phase {
                Pending = 1;
                Running = 2;
            }
            message Pod {
                optional string name = 2;
                optional Phase phase = 1;
                map<string, string> labels = 3;
            }
        "#;
        let rendered = generate_from_sources(&[proto], "v1.37.1", "deadbeef");
        assert!(rendered.contains("(\"k8s.io.api.core.v1.Pod\", &["));
        assert!(rendered.contains(
            "FieldDef::typed(1, \"phase\", WireKind::Enum, \"k8s.io.api.core.v1.Phase\")"
        ));
        assert!(rendered.contains("FieldDef::scalar(2, \"name\", WireKind::String)"));
        assert!(rendered.contains("FieldDef::map(3, \"labels\", WireKind::String, \"\")"));
        assert!(rendered.contains("(\"k8s.io.api.core.v1.Phase\", &["));
    }
}
